LANGUAGE_INDEX = {'en': 0, 'es': 1, 'de': 2, 'it': 3}


def ui(text):
    language = i18n._CURRENT_LANG
    if language == 'fr':
        return text
    values = LABELS.get(text) or MESSAGES.get(text)
    if values:
        return values[LANGUAGE_INDEX.get(language, 0)]
    return text


def video_count(count, *, completed=False):
    """Format video counts without assuming a shared plural suffix."""
    if completed:
        text = "{count} vidéo terminée" if count == 1 else "{count} vidéos terminées"
    else:
        text = "{count} vidéo" if count == 1 else "{count} vidéos"
    return ui(text).format(count=count)
